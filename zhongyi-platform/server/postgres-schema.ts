// Keep this migration immutable once used. A schema change gets a new migration.
// TEXT timestamps/payloads deliberately preserve legacy JSON digest bytes.
export const POSTGRES_SCHEMA_VERSION = 1;
export const POSTGRES_SCHEMA_SQL = `
CREATE TABLE postgres_migrations (version INTEGER PRIMARY KEY, checksum TEXT NOT NULL, applied_at TEXT NOT NULL);
CREATE TABLE migrations (version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL);
CREATE TABLE ingredients (id TEXT PRIMARY KEY, name TEXT NOT NULL, search_text TEXT NOT NULL,
  payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'));
CREATE TABLE metadata (key TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE editorial_notes (ingredient_id TEXT PRIMARY KEY REFERENCES ingredients(id),
  text TEXT NOT NULL, revision INTEGER NOT NULL CHECK (revision > 0), updated_at TEXT NOT NULL);
CREATE TABLE audit_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_id TEXT NOT NULL REFERENCES ingredients(id),
  action TEXT NOT NULL CHECK (action IN ('note_saved','note_cleared')), revision INTEGER NOT NULL,
  created_at TEXT NOT NULL, actor TEXT NOT NULL DEFAULT 'legacy-local-key');
CREATE TABLE users (id TEXT PRIMARY KEY, username TEXT NOT NULL UNIQUE,
  password_hash TEXT NOT NULL CHECK (password_hash ~ '^[a-f0-9]{128}$'),
  password_salt TEXT NOT NULL CHECK (password_salt ~ '^[a-f0-9]{64}$'),
  role TEXT NOT NULL CHECK (role IN ('admin','editor','reviewer')),
  active SMALLINT NOT NULL CHECK (active IN (0,1)), revision INTEGER NOT NULL CHECK (revision > 0), created_at TEXT NOT NULL);
CREATE TABLE sessions (token_hash TEXT PRIMARY KEY CHECK (token_hash ~ '^[a-f0-9]{64}$'),
  user_id TEXT NOT NULL REFERENCES users(id), csrf_token TEXT NOT NULL CHECK (csrf_token ~ '^[a-f0-9]{64}$'),
  expires_at BIGINT NOT NULL CHECK (expires_at >= 0));
CREATE INDEX sessions_user ON sessions(user_id);
CREATE INDEX sessions_expiry ON sessions(expires_at);
CREATE TABLE login_attempts (key TEXT PRIMARY KEY, attempts INTEGER NOT NULL CHECK (attempts >= 0),
  reset_at BIGINT NOT NULL CHECK (reset_at >= 0));
CREATE TABLE security_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actor TEXT NOT NULL, action TEXT NOT NULL, target TEXT, created_at TEXT NOT NULL);
CREATE TABLE source_records (id TEXT PRIMARY KEY, revision INTEGER NOT NULL CHECK (revision > 0), url TEXT NOT NULL UNIQUE);
CREATE TABLE source_versions (source_id TEXT NOT NULL REFERENCES source_records(id),
  revision INTEGER NOT NULL CHECK (revision > 0), title TEXT NOT NULL, publisher TEXT NOT NULL, url TEXT NOT NULL,
  author_id TEXT NOT NULL REFERENCES users(id), author_name TEXT NOT NULL, created_at TEXT NOT NULL,
  PRIMARY KEY(source_id, revision));
ALTER TABLE source_records ADD CONSTRAINT source_head_version FOREIGN KEY (id, revision)
  REFERENCES source_versions(source_id, revision) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE content_revisions (ingredient_id TEXT NOT NULL REFERENCES ingredients(id),
  revision INTEGER NOT NULL CHECK (revision > 0), payload TEXT NOT NULL CHECK (jsonb_typeof(payload::jsonb) = 'object'),
  digest TEXT NOT NULL, base_release_id TEXT NOT NULL, author_id TEXT NOT NULL REFERENCES users(id),
  author_name TEXT NOT NULL, created_at TEXT NOT NULL, PRIMARY KEY(ingredient_id, revision));
CREATE TABLE revision_sources (ingredient_id TEXT NOT NULL, content_revision INTEGER NOT NULL,
  source_id TEXT NOT NULL, source_revision INTEGER NOT NULL, locator TEXT NOT NULL, position INTEGER NOT NULL CHECK (position >= 0),
  PRIMARY KEY(ingredient_id, content_revision, source_id),
  UNIQUE(ingredient_id, content_revision, position),
  FOREIGN KEY(ingredient_id, content_revision) REFERENCES content_revisions(ingredient_id, revision),
  FOREIGN KEY(source_id, source_revision) REFERENCES source_versions(source_id, revision));
CREATE TABLE content_drafts (ingredient_id TEXT PRIMARY KEY REFERENCES ingredients(id), revision INTEGER NOT NULL,
  lock_version INTEGER NOT NULL CHECK (lock_version > 0),
  state TEXT NOT NULL CHECK (state IN ('draft','submitted','changes_requested','editorial_accepted')),
  owner_id TEXT NOT NULL REFERENCES users(id), owner_name TEXT NOT NULL, updated_at TEXT NOT NULL,
  FOREIGN KEY(ingredient_id, revision) REFERENCES content_revisions(ingredient_id, revision));
CREATE TABLE review_tasks (id TEXT PRIMARY KEY, ingredient_id TEXT NOT NULL, content_revision INTEGER NOT NULL,
  digest TEXT NOT NULL, status TEXT NOT NULL CHECK (status IN ('pending','accepted','returned')),
  submitted_by_id TEXT NOT NULL REFERENCES users(id), submitted_by_name TEXT NOT NULL, submitted_at TEXT NOT NULL,
  reviewed_by_id TEXT REFERENCES users(id), reviewed_by_name TEXT, reviewed_at TEXT, comment TEXT,
  FOREIGN KEY(ingredient_id, content_revision) REFERENCES content_revisions(ingredient_id, revision));
CREATE UNIQUE INDEX one_pending_review ON review_tasks(ingredient_id) WHERE status = 'pending';
CREATE INDEX review_task_queue ON review_tasks(status, submitted_at);
CREATE TABLE workflow_events (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ingredient_id TEXT REFERENCES ingredients(id), source_id TEXT REFERENCES source_records(id), revision INTEGER NOT NULL,
  action TEXT NOT NULL CHECK (action IN ('source_created','source_updated','draft_saved','draft_submitted','review_returned','review_accepted')),
  actor_id TEXT NOT NULL REFERENCES users(id), actor_name TEXT NOT NULL, created_at TEXT NOT NULL);
CREATE TABLE migration_runs (id TEXT PRIMARY KEY, source_digest TEXT NOT NULL, seed_digest TEXT NOT NULL,
  source_schema_version INTEGER NOT NULL, row_counts JSONB NOT NULL, migrated_at TEXT NOT NULL);
CREATE FUNCTION deny_history_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'history records are immutable' USING ERRCODE = '23514'; END; $$;
CREATE TRIGGER immutable_source_version BEFORE UPDATE OR DELETE ON source_versions FOR EACH ROW EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_source_truncate BEFORE TRUNCATE ON source_versions FOR EACH STATEMENT EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_content_revision BEFORE UPDATE OR DELETE ON content_revisions FOR EACH ROW EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_content_truncate BEFORE TRUNCATE ON content_revisions FOR EACH STATEMENT EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_revision_source BEFORE UPDATE OR DELETE ON revision_sources FOR EACH ROW EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_reference_truncate BEFORE TRUNCATE ON revision_sources FOR EACH STATEMENT EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_postgres_migration BEFORE UPDATE OR DELETE ON postgres_migrations FOR EACH ROW EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_postgres_migration_truncate BEFORE TRUNCATE ON postgres_migrations FOR EACH STATEMENT EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_migration_run BEFORE UPDATE OR DELETE ON migration_runs FOR EACH ROW EXECUTE FUNCTION deny_history_change();
CREATE TRIGGER immutable_migration_run_truncate BEFORE TRUNCATE ON migration_runs FOR EACH STATEMENT EXECUTE FUNCTION deny_history_change();
`;
